/**
 * The gift's public contract.
 *
 * Shared by the route handlers and the client, so it must stay free of database
 * imports and of every secret. Everything here is either a shape the browser may see
 * or a pure function over untrusted input.
 */

import type { GardenEntry } from "./garden";

/** One photograph. The storage path is private; the URL is signed and short-lived. */
export type GiftPhoto = {
  /** object path inside the private bucket */
  path: string;
  /** alt text, written by the sender, shown to whoever cannot see the picture */
  alt: string;
  /** intrinsic aspect ratio, so the layout does not jump while the image loads */
  ratio: number;
};

/** The voice note. Same deal: a private path, a duration, and a signed URL on read. */
export type GiftVoice = {
  path: string;
  /** seconds, rounded */
  duration: number;
};

/**
 * One video.
 *
 * We never host or proxy video: a gift page that streams four minutes of MP4 from a
 * serverless function is a gift page that costs money to open. The sender supplies a
 * link to something they already own, and the page embeds it by id.
 */
export type GiftVideo = {
  provider: "youtube";
  id: string;
  title: string | null;
};

/** A signed, short-lived URL. Present only in a response that has cleared the PIN. */
export type Signed<T> = T & { url: string };

export type GiftMedia = {
  photos: Signed<GiftPhoto>[];
  voice: Signed<GiftVoice> | null;
  video: GiftVideo | null;
};

/** What the recipient's page is allowed to know before it has proved anything. */
export type GiftView = GardenEntry & {
  recipient: string | null;
  register: string;
  /** true when the gift is behind a PIN and this response is the envelope only */
  locked: boolean;
  media: GiftMedia;
};

export const PHOTO_LIMIT = 5;

/**
 * YouTube ids are exactly eleven characters of URL-safe base64. Parsing them out of a
 * pasted link is worth doing properly: a sender will paste a share URL with a `?si=`
 * tracking tail, or a `youtu.be` short link, or a `/shorts/` path, and a naive split on
 * `=` produces a broken embed.
 */
const YT = /^[A-Za-z0-9_-]{11}$/;

export function parseVideo(input: unknown): GiftVideo | null {
  if (!input || typeof input !== "object") return null;
  const raw = (input as { url?: unknown }).url;
  if (typeof raw !== "string") return null;
  const text = raw.trim();
  if (!text) return null;

  // a bare id is a legitimate paste, and `new URL("dQw4w9WgXcQ")` parses as a hostname
  // rather than throwing — so it has to be checked before any URL parsing happens
  if (YT.test(text)) return { provider: "youtube", id: text, title: readTitle(input) };

  let id: string | null = null;
  try {
    const url = new URL(text.startsWith("http") ? text : `https://${text}`);
    const host = url.hostname.replace(/^www\./, "").replace(/^m\./, "");
    if (host === "youtu.be") {
      id = url.pathname.slice(1).split("/")[0] ?? null;
    } else if (host === "youtube.com" || host === "music.youtube.com") {
      const v = url.searchParams.get("v");
      if (v) id = v;
      else {
        // /shorts/<id>, /embed/<id>, /live/<id>
        const parts = url.pathname.split("/").filter(Boolean);
        if (parts.length >= 2) id = parts[1];
      }
    }
  } catch {
    // not a URL: maybe they pasted the bare id
    id = text;
  }

  if (!id || !YT.test(id)) return null;
  return { provider: "youtube", id, title: readTitle(input) };
}

function readTitle(input: unknown): string | null {
  const title = (input as { title?: unknown }).title;
  return typeof title === "string" && title.trim() ? title.trim().slice(0, 120) : null;
}

/** A safe alt text: stripped of control characters and angle brackets, then bounded. */
export function cleanText(input: unknown, max: number): string {
  if (typeof input !== "string") return "";
  return input
    .replace(/[\u0000-\u001f\u007f<>]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, max);
}

/**
 * Storage paths are generated by the server, never accepted from the client: a path is a
 * capability here, and a path the client chose could point at somebody else's photograph.
 */
export function photoPath(code: string, index: number, ext: string): string {
  return `${code}/photo-${index}.${ext}`;
}

export function voicePath(code: string): string {
  return `${code}/voice.webm`;
}

export const ALLOWED_PHOTO_TYPES = ["image/jpeg", "image/png", "image/webp", "image/avif"] as const;
export const ALLOWED_VOICE_TYPES = ["audio/webm", "audio/mp4", "audio/mpeg", "audio/ogg", "audio/wav"] as const;

export function extensionFor(mime: string): string {
  switch (mime) {
    case "image/jpeg":
      return "jpg";
    case "image/png":
      return "png";
    case "image/avif":
      return "avif";
    case "audio/mp4":
      return "m4a";
    case "audio/mpeg":
      return "mp3";
    case "audio/ogg":
      return "ogg";
    case "audio/wav":
      return "wav";
    default:
      return "webp";
  }
}

/** Signed URLs last long enough to read a letter and look at five photographs. */
export const SIGNED_URL_TTL = 60 * 60; // one hour
